# Стартовый набор: первые запуски не должны занимать часы.
DEFAULT_IDS = ["dentistry", "tire", "coffee"]

# «Хиты» для меню: ниши, где чаще всего нужен сайт.
POPULAR_IDS = [
    "dentistry", "tire", "car_service", "coffee", "cafe", "beauty_salon",
    "medical_center", "renovation", "construction", "fitness", "hotel",
    "accounting",
]

_CATEGORIES: dict[str, dict] = {}
_GROUP_TITLES: dict[str, str] = {}
for _group in GROUPS:
    _GROUP_TITLES[_group["id"]] = _group["title"]
    for _id, _label, _query in _group["categories"]:
        if _id in _CATEGORIES:
            raise RuntimeError(f"дубликат id категории: {_id}")
        _CATEGORIES[_id] = {
            "id": _id,
            "label": _label,
            "query": _query,
            "group": _group["id"],
            "group_title": _group["title"],
        }


def catalog() -> dict:
    """Каталог для интерфейса: группы, категории, наборы по умолчанию."""
    groups = [
        {
            "id": group["id"],
            "title": group["title"],
            "categories": [
                {
                    "id": category_id,
                    "label": label,
                    "query": query,
                }
                for category_id, label, query in group["categories"]
            ],
        }
        for group in GROUPS
    ]
    return {
        "groups": groups,
        "total": len(_CATEGORIES),
        "default": [value for value in DEFAULT_IDS if value in _CATEGORIES],
        "popular": [value for value in POPULAR_IDS if value in _CATEGORIES],
    }


def _expand_ids(category_ids: Iterable[str]) -> list[str]:
    """Развернуть ``all``/``*`` и убрать повторы, сохранив порядок каталога."""
    raw = [str(value).strip() for value in category_ids if str(value).strip()]
    if any(value in {"all", "*", "все"} for value in raw):
        return list(_CATEGORIES)

    requested = set(raw)
    unknown = sorted(value for value in requested if value not in _CATEGORIES)
    if unknown:
        raise ValueError("неизвестные категории: " + ", ".join(unknown))

    # Порядок не кликов, а каталога: сканирование предсказуемо.
    return [category_id for category_id in _CATEGORIES if category_id in requested]


def resolve_queries(
    category_ids: Iterable[str] | None = None,
    custom_query: str | None = None,
) -> list[str]:
    """Превратить выбранные категории и свой запрос в список для карт."""
    ids = _expand_ids(category_ids or [])
    queries: list[str] = [_CATEGORIES[category_id]["query"] for category_id in ids]

    custom = " ".join(str(custom_query or "").split())
    if custom:
        queries.append(custom)

    # Один и тот же текст не должен сканироваться дважды.
    unique: list[str] = []
    seen: set[str] = set()
    for query in queries:
        key = query.casefold()
        if key in seen:
            continue
        seen.add(key)
        unique.append(query)

    if len(unique) > 300:
        raise ValueError("слишком много запросов: максимум 300 за один скан")
    return unique


def category_label(category_id: str) -> str:
    """Название категории по id (для отчётов и логов)."""
    item = _CATEGORIES.get(category_id)
    return item["label"] if item else category_id
